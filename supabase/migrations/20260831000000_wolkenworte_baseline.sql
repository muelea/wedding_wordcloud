do $global_setup$
declare
  table_name text;
begin
  if current_schema() <> 'public' then
    return;
  end if;

  if not exists (select 1 from pg_roles where rolname = 'wolkenworte_runtime') then
    create role wolkenworte_runtime
      nologin nosuperuser nocreatedb nocreaterole noinherit;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'wolkenworte_app') then
    create role wolkenworte_app
      nologin nosuperuser nocreatedb nocreaterole inherit;
  end if;

  execute 'grant wolkenworte_runtime to wolkenworte_app';
  execute 'alter role wolkenworte_app set search_path = public';
  execute 'alter role wolkenworte_app set statement_timeout = ''10s''';
  execute 'alter role wolkenworte_app set lock_timeout = ''5s''';
  execute 'revoke create on schema public from public';
  execute 'revoke create on schema public from wolkenworte_runtime';
  execute 'revoke create on schema public from wolkenworte_app';

  foreach table_name in array array[
    'app_schema_versions',
    'events',
    'words',
    'word_contributions',
    'archives',
    'reserved_event_slugs',
    'admin_pin_failures',
    'configurations',
    'checkout_quotes',
    'orders',
    'checkout_order_shipments',
    'order_items',
    'stripe_webhook_events',
    'print_artifacts',
    'maintenance_runs',
    'printful_webhook_events',
    'provider_smoke_runs',
    'email_jobs',
    'resend_webhook_events',
    'email_smoke_runs',
    'operator_actions'
  ]
  loop
    execute format(
      'grant select, insert, update, delete on table public.%I to wolkenworte_runtime',
      table_name
    );
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists wolkenworte_runtime_all on public.%I', table_name);
    execute format(
      'create policy wolkenworte_runtime_all on public.%I for all to wolkenworte_runtime using (true) with check (true)',
      table_name
    );
  end loop;

  execute 'grant usage on schema public to wolkenworte_runtime';
  execute 'grant usage, select on all sequences in schema public to wolkenworte_runtime';
  execute 'grant execute on all functions in schema public to wolkenworte_runtime';
  execute 'alter default privileges in schema public grant select, insert, update, delete on tables to wolkenworte_runtime';
  execute 'alter default privileges in schema public grant usage, select on sequences to wolkenworte_runtime';
  execute 'alter default privileges in schema public grant execute on functions to wolkenworte_runtime';
  execute 'revoke all on table public.wolkenworte_migrations from wolkenworte_runtime';

  if to_regclass('storage.buckets') is null then
    raise exception 'Supabase Storage schema is missing';
  end if;
  insert into storage.buckets (
    id,
    name,
    public,
    file_size_limit,
    allowed_mime_types
  ) values (
