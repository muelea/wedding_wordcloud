create function set_event_expiry()
returns trigger
language plpgsql
as $$
begin
  new.created_at := coalesce(new.created_at, transaction_timestamp());
  new.expires_at := new.created_at + interval '365 days';
  return new;
end
$$;

create trigger events_set_expiry
before insert or update of created_at, expires_at on events
for each row execute function set_event_expiry();

