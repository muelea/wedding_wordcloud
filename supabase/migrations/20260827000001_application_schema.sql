-- Schema-relative Wolkenworte application objects. Keep this migration free
-- of project-global roles, extensions, Cron jobs and Storage declarations so
-- the test suite can apply it safely to one isolated schema per test file.

create table app_schema_versions (
  version     bigint primary key,
  applied_at  timestamptz not null default transaction_timestamp()
);

insert into app_schema_versions (version) values (1);

create table events (
  id              bigint generated by default as identity primary key,
  slug            text not null unique,
  couple_name     text not null,
  admin_pin_hash  text not null,
  admin_pin_salt  text not null,
  locale          text not null default 'de',
  theme           text not null default 'pastel',
  created_at      timestamptz not null,
  expires_at      timestamptz not null,
  constraint events_slug_nonempty check (length(slug) between 1 and 120),
  constraint events_locale_supported check (locale in ('de', 'en', 'fr', 'it', 'es', 'tr')),
  constraint events_expiry_exact check (expires_at = created_at + interval '365 days')
);

create function set_event_expiry()
returns trigger
language plpgsql
as $$
begin
  new.created_at := coalesce(new.created_at, transaction_timestamp());
  new.expires_at := new.created_at + interval '365 days';
  return new;
end
$$;

create trigger events_set_expiry
before insert or update of created_at, expires_at on events
for each row execute function set_event_expiry();

create index events_expires_at_idx on events (expires_at, id);

create table words (
  id          bigint generated by default as identity primary key,
  event_id    bigint not null references events(id) on delete cascade,
  word        text not null,
  count       integer not null default 1,
  updated_at  timestamptz not null default transaction_timestamp(),
  constraint words_count_positive check (count > 0),
  constraint words_event_word_unique unique (event_id, word)
);

create table word_contributions (
  receipt_id  text primary key,
  event_id    bigint not null,
  word        text not null,
  owner_id    text not null,
  created_at  timestamptz not null default transaction_timestamp(),
  constraint word_contributions_word_fk
    foreign key (event_id, word) references words(event_id, word) on delete cascade
);

create index word_contributions_owner_idx
  on word_contributions (event_id, owner_id, created_at, receipt_id);

create table archives (
  id          bigint generated by default as identity primary key,
