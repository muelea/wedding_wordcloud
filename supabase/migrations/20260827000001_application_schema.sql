  words_json  jsonb not null,
  created_at  timestamptz not null default transaction_timestamp()
);

create index archives_event_created_idx on archives (event_id, created_at);

create table configurations (
  id                    text primary key,
  event_id              bigint references events(id) on delete restrict,
  product_key           text not null,
  printful_variant_id   integer not null,
  quantity              integer not null default 2,
  unit_price_cents      integer not null default 0,
  theme                 text not null,
  words_json            jsonb not null,
  design_json           jsonb not null,
  configuration_type    text not null default 'event_wordcloud',
  orientation           text not null default 'default',
  print_width           integer not null,
  print_height          integer not null,
  created_at            timestamptz not null default transaction_timestamp(),
  constraint configurations_quantity_valid check (quantity between 1 and 99),
  constraint configurations_dimensions_valid check (print_width > 0 and print_height > 0),
  constraint configurations_type_valid
    check (configuration_type in ('event_wordcloud', 'personal_memory'))
);

create index configurations_event_created_idx
  on configurations (event_id, created_at, id);

