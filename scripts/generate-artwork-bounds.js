'use strict';

// Run after deliberately updating the pinned emoji/motif artwork. These small,
// conservative ink rectangles are identical in browsers and server validation.
const fs = require('node:fs');
const path = require('node:path');
const { createCanvas, Image } = require('canvas');
const EmojiData = require('../public/js/emoji-data');
const Icons = require('../public/js/mug-icons');
const { loadBrowserSvg } = require('../src/emojiBrowserAssets');

const RESOLUTION = 512;
const canvas = createCanvas(RESOLUTION, RESOLUTION);
const ctx = canvas.getContext('2d');

function bounds(source) {
  const image = new Image();
  image.src = Buffer.from(source);
  ctx.clearRect(0, 0, RESOLUTION, RESOLUTION);
  // Match contain() in the browser and the nested immutable SVG viewport.
  const scale = RESOLUTION / Math.max(image.width, image.height);
  const width = image.width * scale, height = image.height * scale;
  ctx.drawImage(image, (RESOLUTION - width) / 2, (RESOLUTION - height) / 2, width, height);
  const pixels = ctx.getImageData(0, 0, RESOLUTION, RESOLUTION).data;
  let left = RESOLUTION, top = RESOLUTION, right = 0, bottom = 0;
  for (let y = 0; y < RESOLUTION; y++) for (let x = 0; x < RESOLUTION; x++) {
    if (!pixels[(y * RESOLUTION + x) * 4 + 3]) continue;
    left = Math.min(left, x); top = Math.min(top, y);
    right = Math.max(right, x + 1); bottom = Math.max(bottom, y + 1);
  }
  if (right <= left || bottom <= top) throw new Error('Empty bundled artwork');
  // One sample pixel protects vector edges between samples, at every print size.
  return [Math.max(0, left - 1), Math.max(0, top - 1),
    Math.min(RESOLUTION, right + 1), Math.min(RESOLUTION, bottom + 1)];
}

async function main() {
  const emoji = {};
  for (const asset of [...new Set(Object.values(EmojiData.canonicalAssets))].sort()) {
    emoji[asset] = bounds(await loadBrowserSvg(asset));
  }
  const icons = {};
  for (const icon of Icons.ICONS) {
    icons[icon.id] = bounds(`<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">` +
      `<path d="${icon.path}" fill="none" stroke="black" stroke-width="${Icons.STROKE_WIDTH}" ` +
      'stroke-linecap="round" stroke-linejoin="round"/></svg>');
  }
  const data = { resolution: RESOLUTION, artworkVersion: EmojiData.artworkVersion, emoji, icons };
  const serialized = JSON.stringify(data, null, 2).replace(/\[\n\s+(\d+),\n\s+(\d+),\n\s+(\d+),\n\s+(\d+)\n\s+\]/g,
    '[$1,$2,$3,$4]');
  fs.writeFileSync(path.join(__dirname, '../public/js/artwork-bounds-data.js'),
    '// Generated by scripts/generate-artwork-bounds.js from pinned artwork.\n' +
    '(function(root){\n  const data = ' + serialized + ';\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = data;\n" +
    "  else root.ArtworkBoundsData = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n");
  console.log(`Measured ${Object.keys(emoji).length} emoji and ${Object.keys(icons).length} motifs.`);
}
if (require.main === module) main().catch(error => { console.error(error); process.exitCode = 1; });
